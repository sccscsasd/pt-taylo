# -*- coding: utf-8 -*-
"""Перевод карточек колоды на другой язык: партиями, с проверкой каждой.

Переводится оборот карточки — перевод, перевод примера и заметка. Слово и пример
по-португальски у карточки одни на все языки и не трогаются.

    python vocabulario/traduzir.py stat            сводка по всем языкам и колодам
    python vocabulario/traduzir.py en stat         один язык по всем колодам
    python vocabulario/traduzir.py en a2 next 80   показать следующие непереведённые
    python vocabulario/traduzir.py en a2 add       влить партию из _en-porcao.json
    python vocabulario/traduzir.py en check        чек-лист по всем колодам
    python vocabulario/traduzir.py en a2 check     замечания только по этой колоде

Язык первым аргументом, ключ колоды вторым; регистр не важен. Без ключа колоды
работают stat и check — им есть что сказать обо всех пяти колодах разом.

Партия — _<язык>-porcao.json, список объектов {"word", "<язык>", "ex<язык>",
"note<язык>"}. JSON, а не питоновские кортежи, как у соседних инструментов: здесь
переводится проза с кавычками, тире и апострофами, и одно правило экранирования
надёжнее двух.

add не пишет ничего, пока есть хоть одно замечание: колода уже в базе, чинить
её потом дороже, чем переписать партию сейчас. Занятость перевода он проверяет
по всем пяти колодам, а не только по своей: одинаковый перевод у двух карточек —
ловушка режима RU→PT, и границы колоды она не знает.

Раньше это был uk.py, знавший один язык. Языков стало два, и копировать двести
строк проверок под каждый следующий не годится: язык теперь параметр, а всё, что
у языка своё, лежит в ЯЗЫКИ ниже — колонки и проверка на непереведённый кусок.
"""

import io
import json
import os
import re
import sys

ЗДЕСЬ = os.path.dirname(os.path.abspath(__file__))
КЛЮЧИ = ("a1", "a2", "b1", "b2", "c1")
КОЛОДЫ = {к: os.path.join(ЗДЕСЬ, "baralho-completo-%s.json" % к.upper()) for к in КЛЮЧИ}

# Буквы, которых в украинском алфавите нет вовсе: их появление означает, что кусок
# остался русским. Обратная проверка (є, і, ї, ґ) ничего не доказывает — «банк»
# и «Лісабон» пишутся без них. У английского проверка проще и строже: кириллица
# в английском переводе не может быть ничем, кроме недоделанной работы.
НЕ_УКРАИНСКИЕ = re.compile("[ыэъё]", re.I)
КИРИЛЛИЦА = re.compile("[а-яёіїєґ]", re.I)

ЯЗЫКИ = {
    "uk": {
        "имя": "украинский",
        "поля": ("uk", "exuk", "noteuk"),
        "чужое": НЕ_УКРАИНСКИЕ,
        "чужое_что": "русская буква",
        # Совпасть с русским может и слово, и даже фраза («банк», «суп», «ж. р.»),
        # но не все три поля разом — это уже не совпадение, а непереведённая карточка.
        "русский_насквозь": True,
        "разбег": 4,
    },
    "en": {
        "имя": "английский",
        "поля": ("en", "exen", "noteen"),
        "чужое": КИРИЛЛИЦА,
        "чужое_что": "кириллица",
        # У английского совпадений с русским не бывает вовсе, эту проверку заменяет
        # кириллица: она ловит и недоделанное, и просто забытое поле.
        "русский_насквозь": False,
        # Английский на артиклях и вспомогательных длиннее там, где русский обходится
        # падежом, и короче там, где русский многословен. Пять слов вместо четырёх —
        # чтобы честный перевод не спотыкался о проверку.
        "разбег": 5,
    },
}


def порция_файл(язык):
    return os.path.join(ЗДЕСЬ, "_%s-porcao.json" % язык)


def читать(ключ):
    return json.load(io.open(КОЛОДЫ[ключ], encoding="utf-8"))


def писать(ключ, d):
    with io.open(КОЛОДЫ[ключ], "w", encoding="utf-8", newline="\n") as f:
        json.dump(d, f, ensure_ascii=False, indent=1)
        f.write("\n")


def все_карточки():
    """Карточки всех колод парами (ключ колоды, карточка)."""
    out = []
    for к in КЛЮЧИ:
        out += [(к, c) for c in читать(к)["cards"]]
    return out


def слов(s):
    return len([x for x in re.split(r"\s+", s.strip()) if x])


def переведена(c, я):
    return bool((c.get(ЯЗЫКИ[я]["поля"][0]) or "").strip())


def next_(язык, ключ, n):
    я = ЯЗЫКИ[язык]
    d = читать(ключ)
    ждут = [c for c in d["cards"] if not переведена(c, язык)]
    print("колода %s, без %s перевода: %d из %d"
          % (ключ.upper(), я["имя"], len(ждут), len(d["cards"])))
    print("формат: слово | часть речи | перевод | пример | перевод примера | заметка")
    print()
    for i, c in enumerate(ждут[:n], 1):
        print("%3d. %s | %s | %s | %s | %s | %s"
              % (i, c["word"], c.get("pos", ""), c.get("ru", ""),
                 c.get("ex", ""), c.get("exru", ""), c.get("note", "")))


def add(язык, ключ):
    я = ЯЗЫКИ[язык]
    поле, поле_ех, поле_зам = я["поля"]
    d = читать(ключ)
    карты = {c["word"]: c for c in d["cards"]}
    порция = json.load(io.open(порция_файл(язык), encoding="utf-8"))
    в_партии = {(p.get("word") or "").strip() for p in порция}

    # Чем уже занят перевод: все колоды сразу. Карточки самой партии из занятого
    # исключаются — иначе при повторном вливании карточка спорила бы сама с собой.
    занято, занято_пример = {}, {}
    for к, c in все_карточки():
        if not переведена(c, язык) or (к == ключ and c["word"] in в_партии):
            continue
        занято.setdefault(c[поле].strip().lower(), (к, c["word"]))
        пр = (c.get(поле_ех) or "").strip().lower()
        if пр:
            занято_пример.setdefault(пр, (к, c["word"]))

    замечания = []
    видели = set()
    свои_переводы, свои_примеры = {}, {}
    for i, p in enumerate(порция, 1):
        сл = (p.get("word") or "").strip()
        пер = (p.get(поле) or "").strip()
        прим = (p.get(поле_ех) or "").strip()
        зам = (p.get(поле_зам) or "").strip()
        где = "%d. %s" % (i, сл or "(без слова)")

        c = карты.get(сл)
        if c is None:
            замечания.append("%s — такого слова в колоде %s нет" % (где, ключ.upper()))
            continue
        if сл in видели:
            замечания.append("%s — повторяется внутри партии" % где)
            continue
        видели.add(сл)

        if not пер:
            замечания.append("%s — пустой перевод" % где)
        if not прим:
            замечания.append("%s — пустой перевод примера" % где)
        if c.get("note") and not зам:
            замечания.append("%s — заметка есть по-русски, но не переведена" % где)
        if зам and not c.get("note"):
            замечания.append("%s — заметка появилась из ниоткуда" % где)

        for имя_поля, текст in (("перевод", пер), ("пример", прим), ("заметка", зам)):
            м = я["чужое"].search(текст)
            if м:
                замечания.append("%s — в поле «%s» %s «%s»: %s"
                                 % (где, имя_поля, я["чужое_что"], м.group(0), текст))

        if (я["русский_насквозь"] and пер == c.get("ru", "")
                and прим == c.get("exru", "") and зам == (c.get("note") or "")):
            замечания.append("%s — все три поля совпали с русскими" % где)

        разница = abs(слов(прим) - слов(c.get("exru", "")))
        if разница > я["разбег"]:
            замечания.append("%s — пример разошёлся с русским на %d слов: «%s» против «%s»"
                             % (где, разница, прим, c.get("exru", "")))
        if len(зам) > 90:
            замечания.append("%s — заметка длиннее 90 символов (%d)" % (где, len(зам)))

        # Одинаковый перевод у двух карточек — ловушка RU→PT: человек видит одно
        # слово, а правильных ответов два, засчитывается один. Разводим сразу.
        k = пер.lower()
        if k and k in занято:
            чей = занято[k]
            замечания.append("%s — перевод «%s» уже у «%s» (колода %s)"
                             % (где, пер, чей[1], чей[0].upper()))
        elif k and k in свои_переводы:
            замечания.append("%s — перевод «%s» уже у «%s» в этой же партии"
                             % (где, пер, свои_переводы[k]))
        elif k:
            свои_переводы[k] = сл

        kp = прим.lower()
        if kp and kp in занято_пример:
            чей = занято_пример[kp]
            замечания.append("%s — такой же перевод примера у «%s» (колода %s)"
                             % (где, чей[1], чей[0].upper()))
        elif kp and kp in свои_примеры:
            замечания.append("%s — такой же перевод примера у «%s» в этой же партии"
                             % (где, свои_примеры[kp]))
        elif kp:
            свои_примеры[kp] = сл

    if замечания:
        print("партия не влита, замечаний %d:" % len(замечания))
        for з in замечания:
            print("  " + з)
        return 1

    for p in порция:
        c = карты[p["word"].strip()]
        c[поле] = (p.get(поле) or "").strip()
        c[поле_ех] = (p.get(поле_ех) or "").strip()
        c[поле_зам] = (p.get(поле_зам) or "").strip()

    писать(ключ, d)
    осталось = sum(1 for c in d["cards"] if not переведена(c, язык))
    print("влито карточек: %d, в колоде %s переведено %d из %d, осталось %d"
          % (len(порция), ключ.upper(),
             len(d["cards"]) - осталось, len(d["cards"]), осталось))
    return 0


def stat(язык=None, ключ=None):
    языки = [язык] if язык else list(ЯЗЫКИ)
    if ключ is None:
        print("колода  карточек  " + "  ".join("%-14s" % ЯЗЫКИ[я]["имя"] for я in языки))
        итог = {я: 0 for я in языки}
        всего = 0
        for к in КЛЮЧИ:
            c = читать(к)["cards"]
            всего += len(c)
            строка = "%-6s  %8d  " % (к.upper(), len(c))
            for я in языки:
                есть = sum(1 for x in c if переведена(x, я))
                итог[я] += есть
                строка += "%6d (%3.0f%%)  " % (есть, 100.0 * есть / len(c))
            print(строка)
        строка = "%-6s  %8d  " % ("всего", всего)
        for я in языки:
            строка += "%6d (%3.0f%%)  " % (итог[я], 100.0 * итог[я] / всего)
        print(строка)
        for я in языки:
            print("осталось перевести на %s: %d" % (ЯЗЫКИ[я]["имя"], всего - итог[я]))
        return

    c = читать(ключ)["cards"]
    print("колода %s: %d карточек" % (ключ.upper(), len(c)))
    for я in языки:
        поле, _, поле_зам = ЯЗЫКИ[я]["поля"]
        есть = sum(1 for x in c if переведена(x, я))
        зам = sum(1 for x in c if (x.get(поле_зам) or "").strip())
        print("%s: %d (%.0f%%), заметок %d" % (ЯЗЫКИ[я]["имя"], есть,
                                               100.0 * есть / len(c), зам))
    print("русских заметок: %d" % sum(1 for x in c if x.get("note")))


def check(язык, ключ=None):
    """Чек-лист по всем колодам разом.

    Одинаковый перевод ищется по всей базе слов, а не внутри одной колоды: человек
    учит несколько колод сразу, и ловушка RU→PT границы колоды не знает. Ключ
    колоды сужает не поиск, а вывод — спор показывается, если хоть одна из
    спорящих карточек из этой колоды.
    """
    я = ЯЗЫКИ[язык]
    поле, поле_ех, поле_зам = я["поля"]
    пары = [(к, x) for к, x in все_карточки() if переведена(x, язык)]
    беды = []

    def свои(*кто):
        return ключ is None or ключ in кто

    def имя(к, x):
        return "%s (%s)" % (x["word"], к.upper())

    # 1. одинаковый перевод у разных карточек — ловушка режима RU→PT
    видели = {}
    for к, x in пары:
        видели.setdefault(x[поле].strip().lower(), []).append((к, x))
    for k, спор in sorted(видели.items()):
        if len(спор) > 1 and свои(*[к for к, _ in спор]):
            беды.append("одинаковый перевод «%s»: %s"
                        % (k, ", ".join(имя(к, x) for к, x in спор)))

    # 2. чужие буквы: у украинского русские, у английского любая кириллица
    for к, x in пары:
        if not свои(к):
            continue
        for п in (поле, поле_ех, поле_зам):
            м = я["чужое"].search(x.get(п) or "")
            if м:
                беды.append("%s — %s «%s» в %s: %s"
                            % (имя(к, x), я["чужое_что"], м.group(0), п, x.get(п)))

    # 3. пустые поля там, где по-русски не пусто
    for к, x in пары:
        if not свои(к):
            continue
        if not (x.get(поле_ех) or "").strip():
            беды.append("%s — нет перевода примера" % имя(к, x))
        if x.get("note") and not (x.get(поле_зам) or "").strip():
            беды.append("%s — нет переведённой заметки" % имя(к, x))

    # 4. повторяющиеся примеры
    примеры = {}
    for к, x in пары:
        примеры.setdefault((x.get(поле_ех) or "").strip().lower(), []).append((к, x))
    for k, спор in sorted(примеры.items()):
        if k and len(спор) > 1 and свои(*[к for к, _ in спор]):
            беды.append("повторяется пример «%s»: %s"
                        % (k, ", ".join(имя(к, x) for к, x in спор)))

    # 5. заметки длиннее 90
    for к, x in пары:
        if свои(к) and len(x.get(поле_зам) or "") > 90:
            беды.append("%s — заметка %d символов" % (имя(к, x), len(x[поле_зам])))

    охват = ("колоде " + ключ.upper()) if ключ else "всем колодам"
    print("проверено переведённых карточек: %d (%s), замечания по %s"
          % (len(пары), я["имя"], охват))
    if not беды:
        print("замечаний нет")
        return 0
    print("замечаний: %d" % len(беды))
    for б in беды:
        print("  " + б)
    return 1


if __name__ == "__main__":
    арг = sys.argv[1:]
    язык = ключ = None
    if арг and арг[0].lower() in ЯЗЫКИ:
        язык = арг.pop(0).lower()
    if арг and арг[0].lower() in КОЛОДЫ:
        ключ = арг.pop(0).lower()
    цель = арг[0] if арг else "stat"

    if цель == "stat":
        stat(язык, ключ)
    elif язык is None:
        sys.exit("какой язык? %s" % ", ".join(ЯЗЫКИ))
    elif цель == "next":
        if ключ is None:
            sys.exit("next — про одну колоду: python vocabulario/traduzir.py en a2 next 80")
        next_(язык, ключ, int(арг[1]) if len(арг) > 1 else 50)
    elif цель == "add":
        if ключ is None:
            sys.exit("add — про одну колоду: python vocabulario/traduzir.py en a2 add")
        sys.exit(add(язык, ключ))
    elif цель == "check":
        sys.exit(check(язык, ключ))
    else:
        sys.exit("что делать? next, add, stat или check (колоды: %s)" % ", ".join(КЛЮЧИ))
