-- Английский перевод карточек: ещё три колонки рядом с русскими и украинскими.
--
-- Форма та же, что у миграции 016: слово и пример по-португальски у карточки одни,
-- меняется только оборот — перевод, перевод примера и заметка. Поэтому не вторая
-- таблица и не строка на язык, а три колонки в той же строке.
--
-- Почему снова колонки, а не одна `tr jsonb`. При трёх языках колонки ещё выигрывают:
-- перевод видно в таблице глазами, генератор и клиент правятся в одну строку, докачка
-- по updated_at не меняется. Выигрыш jsonb начинается языка с четвёртого, когда колонок
-- содержания станет двенадцать и каждый новый язык — это миграция на всю таблицу.
-- Переезд туда, если понадобится, стоит одной миграции: колонки читаются, jsonb пишется.
--
-- Пустая колонка — это «перевода пока нет»: клиент в таком случае показывает русский,
-- поэтому до первой залитой колоды английский интерфейс работает ровно как работал.
--
-- Часть речи (pos) сюда не входит по той же причине, что и в 016: одиннадцать значений
-- на пять колод — закрытый список, он переводится словарём интерфейса.

begin;

alter table public.pt_words
  add column if not exists en     text not null default '',
  add column if not exists exen   text not null default '',
  add column if not exists noteen text not null default '';

commit;

-- PostgREST держит схему в кеше и после DDL какое-то время отдаёт старый набор колонок.
notify pgrst, 'reload schema';

select count(*) as слов,
       count(*) filter (where uk <> '') as с_украинским,
       count(*) filter (where en <> '') as с_английским
  from public.pt_words;
