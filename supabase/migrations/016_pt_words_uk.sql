-- Украинский перевод карточек: три колонки рядом с русскими.
--
-- Слово и пример по-португальски у карточки одни, меняется только то, что на обороте:
-- перевод, перевод примера и заметка. Поэтому не вторая таблица и не строка на язык,
-- а три колонки в той же строке: слово остаётся одним объектом, id по-прежнему выводится
-- из самого слова, и докачка по updated_at работает как работала.
--
-- Пустая колонка — это «перевода пока нет»: клиент в таком случае показывает русский,
-- поэтому колоды без украинского продолжают работать без единой правки.
--
-- Часть речи (pos) сюда не входит намеренно: значений одиннадцать на пять колод,
-- это закрытый список, и он переводится словарём интерфейса, а не хранится у каждого
-- слова одиннадцатью повторами.

begin;

alter table public.pt_words
  add column if not exists uk     text not null default '',
  add column if not exists exuk   text not null default '',
  add column if not exists noteuk text not null default '';

commit;

-- PostgREST держит схему в кеше и после DDL какое-то время отдаёт старый набор колонок.
notify pgrst, 'reload schema';

select count(*) as слов,
       count(*) filter (where uk <> '') as с_украинским
  from public.pt_words;
